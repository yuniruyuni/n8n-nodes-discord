export function calculateIntents(event: string, selectedIntents: string[] = []): number {
	const names = selectedIntents.length > 0 ? selectedIntents : (EVENT_INTENTS[event] ?? ['GUILDS']);
	return names.reduce((total, name) => total | GATEWAY_INTENTS[name as GatewayIntentName], 0);
}
