export type GatewayIntentName = keyof typeof GATEWAY_INTENTS;

export const gatewayIntentOptions = Object.entries(GATEWAY_INTENTS).map(([name, value]) => ({
	name: name
		.toLowerCase()
		.split('_')
		.map((part) => part.charAt(0).toUpperCase() + part.slice(1))
		.join(' '),
	value: name,
	description: `${name} (${value})`,
}));

